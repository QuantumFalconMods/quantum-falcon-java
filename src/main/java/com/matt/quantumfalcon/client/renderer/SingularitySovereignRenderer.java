package com.matt.quantumfalcon.client.renderer;

import com.matt.quantumfalcon.client.model.SingularitySovereignModel;
import com.matt.quantumfalcon.entity.boss.SingularitySovereignEntity;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

public class SingularitySovereignRenderer extends GeoEntityRenderer<SingularitySovereignEntity> {

    public SingularitySovereignRenderer(EntityRendererProvider.Context context) {
        super(context, new SingularitySovereignModel());

        // Emissive map: singularity_sovereign_glowmask.png (generated by tools/gen_sovereign.py)
        this.addRenderLayer(new PulsingGlowLayer<>(this));

        this.shadowRadius = 2.8f;
        this.scaleWidth = this.scaleHeight = 1.0f; // rebuilt rig is modelled at native size for the 2.5x4 hitbox
    }

    @Override
    public ResourceLocation getTextureLocation(SingularitySovereignEntity animatable) {
        return ResourceLocation.fromNamespaceAndPath("quantumfalcon", "textures/entity/boss/singularity_sovereign.png");
    }
}

