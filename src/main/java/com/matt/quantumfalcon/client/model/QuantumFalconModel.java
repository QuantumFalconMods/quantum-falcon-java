package com.matt.quantumfalcon.client.model;

import com.matt.quantumfalcon.QuantumFalcon;
import com.matt.quantumfalcon.entity.QuantumFalconEntity;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.model.GeoModel;

import java.util.Set;

public class QuantumFalconModel extends GeoModel<QuantumFalconEntity> {

    private static final ResourceLocation GEO = ResourceLocation.fromNamespaceAndPath(
            QuantumFalcon.MOD_ID, "geo/quantum_falcon.geo.json");

    private static final ResourceLocation ANIMATIONS = ResourceLocation.fromNamespaceAndPath(
            QuantumFalcon.MOD_ID, "animations/quantum_falcon.animation.json");

    /** Default variant texture (peregrine = the original hand-painted palette). */
    private static final ResourceLocation DEFAULT_TEXTURE = ResourceLocation.fromNamespaceAndPath(
            QuantumFalcon.MOD_ID, "textures/entity/quantum_falcon/peregrine.png");

    /** Variant names that have a corresponding .png in textures/entity/quantum_falcon/ */
    private static final Set<String> EXISTING_VARIANTS = Set.of(
            "abyssal", "aetherwing", "coral", "cosmic", "crimson", "deepslate", "entangled_prism",
            "mushroom", "peregrine", "prairie", "quantum_phoenix", "singularity", "soulfire",
            "stormrider", "tempest", "tundra", "voidstalker", "warped",
            "tidecaller", "emberfrost", "sporewraith", "aurora_seraph", "rift_reaver", "chronowing", "nebula_prism", "paradox");

    // v2 rig, animations and textures are generated by tools/gen_falcon_v2.py (original work; see FALCONS.md).
    // Matthew's v1 "quantum falcon 2" assets are archived in art/falcon_v1/.

    @Override
    public ResourceLocation getModelResource(QuantumFalconEntity entity) {
        return entity == null ? GEO : com.matt.quantumfalcon.entity.FalconArchetype.of(entity).geo();
    }

    @Override
    public void setCustomAnimations(QuantumFalconEntity entity, long instanceId, software.bernie.geckolib.animation.AnimationState<QuantumFalconEntity> state) {
        super.setCustomAnimations(entity, instanceId, state);
        if (entity == null) return;
        com.matt.quantumfalcon.entity.FalconArchetype a = com.matt.quantumfalcon.entity.FalconArchetype.of(entity);
        var proc = getAnimationProcessor();
        // Proportions are applied to parent bones so every child (wings, neck, legs, tail) moves and scales with
        // its parent and joints stay closed. No keyframes scale these bones, so absolute values are safe.
        var body = proc.getBone("body");
        if (body != null) { body.setScaleX(a.bodyW); body.setScaleY(a.bodyH); body.setScaleZ(a.bodyW); }
        var head = proc.getBone("head");
        if (head != null) { head.setScaleX(a.head); head.setScaleY(a.head); head.setScaleZ(a.head); }
        for (String w : new String[]{"wing_l", "wing_r"}) {
            var bn = proc.getBone(w);
            if (bn != null) bn.setScaleX(a.wings);
        }
    }

    @Override
    public ResourceLocation getTextureResource(QuantumFalconEntity entity) {
        if (entity == null) {
            return DEFAULT_TEXTURE;
        }
        String variant = entity.getVariant();
        if (variant == null || variant.isEmpty()) {
            variant = "peregrine";
        }
        String key = variant.toLowerCase();
        if (!EXISTING_VARIANTS.contains(key)) {
            return DEFAULT_TEXTURE;
        }
        String prefix = entity.isAnomaly() ? "anomaly_" : "";
        return ResourceLocation.fromNamespaceAndPath(
                QuantumFalcon.MOD_ID,
                "textures/entity/quantum_falcon/" + prefix + key + ".png");
    }

    /** Emissive accent layer for the entity's variant (same UV layout as the base texture). */
    public ResourceLocation getGlowTexture(QuantumFalconEntity entity) {
        String key = entity == null || entity.getVariant() == null ? "peregrine" : entity.getVariant().toLowerCase();
        if (!EXISTING_VARIANTS.contains(key)) key = "peregrine";
        return ResourceLocation.fromNamespaceAndPath(QuantumFalcon.MOD_ID,
                "textures/entity/quantum_falcon/" + key + "_glow.png");
    }

    @Override
    public ResourceLocation getAnimationResource(QuantumFalconEntity entity) {
        return ANIMATIONS;
    }
}

